#!/bin/bash
# Writes Config/Version.xcconfig from package.json's version so the app and
# the extension ship under the same marketing version. Run after bumping
# package.json (scripts/build.sh does it for you) and commit the result.
set -euo pipefail
cd "$(dirname "$0")/.."
VERSION=$(node -p "require('../package.json').version")
printf '// Generated by scripts/sync-version.sh from package.json. Do not edit.\nMARKETING_VERSION = %s\n' "$VERSION" > Config/Version.xcconfig
echo "MARKETING_VERSION = $VERSION"
